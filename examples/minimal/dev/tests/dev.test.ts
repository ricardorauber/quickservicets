import { expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { composeYaml, describeInfrastructure, INFRA_CATALOG, loadConfig, localServicesPlan, type DevOptions } from "@quickservicets/core";
import { describeWithServices, startTestService } from "@quickservicets/cli/testing";

const root = join(import.meta.dir, "..");
const read = (path: string) => readFileSync(join(root, path), "utf8");
const files = () => ({
  "quickservicets.config.ts": read("quickservicets.config.ts"),
  "entities/Post.ts": read("entities/Post.ts"),
  "entities/Attachment.ts": read("entities/Attachment.ts"),
  "queues/notify.ts": read("queues/notify.ts"),
  "endpoints/posts/[id]/notify/post.ts": read("endpoints/posts/[id]/notify/post.ts"),
});
const json = (body: unknown) => ({ method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body) });

/** Waits until a post is marked notified by the queue consumer. */
async function notified(service: { fetch(path: string): Promise<Response> }, id: string): Promise<boolean> {
  const deadline = Date.now() + 15_000;
  while (Date.now() < deadline) {
    if (((await (await service.fetch(`/posts/${id}`)).json()) as { notified: boolean }).notified) return true;
    await Bun.sleep(100);
  }
  return false;
}

const config = await loadConfig(root, {});
const services = describeInfrastructure(config as never).services;

test("the compose document has PostgreSQL and MinIO with their health checks, volumes and ports, without Docker", () => {
  const options = config.features.find((feature) => feature.key === "dev")!.options as unknown as DevOptions;
  const plan = localServicesPlan(config as never, options, root);
  expect(plan.project).toBe("minimal-dev");
  expect(plan.services.map((service) => [service.name, service.image, service.port])).toEqual([
    ["database", INFRA_CATALOG.postgres.image, 5432],
    ["minio", INFRA_CATALOG.minio.image, 9000],
  ]);
  const yaml = composeYaml(plan.document);
  expect(yaml.split("\n")[0]).toBe("# Generated by quickservicets from quickservicets.config.ts. Do not edit.");
  expect(yaml).toContain("pg_isready -U postgres");
  expect(yaml).toContain("name: minimal-dev_database_data");
  expect(yaml).toContain("name: minimal-dev_minio_data");
  expect(plan.document.services.minio!.environment).toMatchObject({ QS_BUCKETS: "uploads" });
  expect(plan.env).toEqual({
    DATABASE_URL: "postgres://postgres:postgres@localhost:5432/app",
    S3_ENDPOINT: "http://localhost:9000",
    S3_ACCESS_KEY_ID: "minioadmin",
    S3_SECRET_ACCESS_KEY: "minioadmin",
    S3_REGION: "us-east-1",
  });
});

test("on the memory database the project serves its posts and consumes its queue", async () => {
  const service = await startTestService({ files: files() });
  try {
    const post = (await (await service.fetch("/posts", json({ title: "Hello" }))).json()) as { id: string };
    expect((await service.fetch(`/posts/${post.id}/notify`, { method: "POST" })).status).toBe(200);
    expect(await notified(service, post.id)).toBe(true);
  } finally {
    await service.stop();
  }
});

describeWithServices(
  ["postgres", "minio"],
  (started) => {
    test("on PostgreSQL and MinIO a file is uploaded and a message is enqueued and consumed", async () => {
      // The containers started for this block are reused through TEST_<KIND>_URL.
      const service = await startTestService({ files: files(), services: ["postgres", "minio"], env: { TEST_POSTGRES_URL: started.urls.postgres!, TEST_MINIO_URL: started.urls.minio! } });
      try {
        const form = new FormData();
        // The PNG signature and a few bytes: Media accepts images.
        const bytes = new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 1, 2, 3, 4, 5, 6, 7, 8]);
        form.append("file", new File([bytes], "pixel.png", { type: "image/png" }));
        form.append("caption", "Greeting");
        const uploaded = await service.fetch("/attachments", { method: "POST", body: form });
        expect(uploaded.status).toBe(201);
        const attachment = (await uploaded.json()) as { id: string; size: number; caption: string };
        expect(attachment).toMatchObject({ size: 16, caption: "Greeting" });
        const download = await service.fetch(`/attachments/${attachment.id}/file`);
        expect(new Uint8Array(await download.arrayBuffer())).toEqual(bytes);
        const post = (await (await service.fetch("/posts", json({ title: "Stored in PostgreSQL" }))).json()) as { id: string };
        expect((await service.fetch(`/posts/${post.id}/notify`, { method: "POST" })).status).toBe(200);
        expect(await notified(service, post.id)).toBe(true);
      } finally {
        await service.stop();
      }
    }, 60_000);
  },
  { services },
);
