import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { describeInfrastructure, resolveInfraEnv, type InfraService } from "../public.ts";

/** The first line of every generated compose file. */
export const COMPOSE_HEADER = "# Generated by quickservicets from quickservicets.config.ts. Do not edit.";

/** The project file passed as a second compose file, so a project changes or adds services without editing generated output. */
export const COMPOSE_OVERRIDE_FILE = "dev/compose.override.yml";

/** The options of the `dev` native the local services read. */
export interface DevOptions {
  services: Record<string, { enabled: boolean; image?: string; port?: number; env?: Record<string, string> }>;
  composeFile: string;
  project?: string;
  wait: string;
}

/** One service started locally: its requirement, image and host port of each container port. */
export interface LocalService {
  name: string;
  kind: string;
  image: string;
  /** The host port of each container port. */
  ports: Record<number, number>;
  /** The host port of the first container port, the one `{port}` names. */
  port: number;
  service: InfraService;
}

/** What `quickservicets dev --services` starts: the compose document, its file and project, and the variables. */
export interface LocalServicesPlan {
  project: string;
  /** The compose file, relative to the project. */
  file: string;
  services: LocalService[];
  /** The compose document as an object, before it is written. */
  document: ComposeDocument;
  /** Every connection variable of the services, resolved for `localhost` and the host ports. */
  env: Record<string, string>;
  /** The same variables with the services' passwords replaced by `[secret]`, for printing. */
  maskedEnv: Record<string, string>;
}

/** A Docker Compose document. */
export interface ComposeDocument {
  name?: string;
  services: Record<string, Record<string, unknown>>;
  volumes?: Record<string, Record<string, unknown>>;
  [key: string]: unknown;
}

/** A compose project name from a package name: lowercase letters, digits, dashes and underscores, starting with a letter or digit. */
export function composeProjectName(packageName: string | undefined): string {
  const bare = (packageName ?? "").replace(/^@[^/]+\//, "").toLowerCase().replace(/[^a-z0-9_-]+/g, "-").replace(/^[^a-z0-9]+/, "").replace(/-+$/, "");
  return bare === "" ? "quickservicets" : bare;
}

/** The package name of the project, or undefined. */
function packageName(root: string): string | undefined {
  const file = join(root, "package.json");
  if (!existsSync(file)) return undefined;
  try {
    return (JSON.parse(readFileSync(file, "utf8")) as { name?: string }).name;
  } catch {
    return undefined;
  }
}

/**
 * The local services of a configuration: every service of its infrastructure description that `services.<name>`
 * does not disable, with the image and host port the options choose. Host ports are the catalog's container ports;
 * a later service needing a host port an earlier one took gets the next one up, unless its option sets one.
 */
export function localServicesPlan(config: Record<string, unknown>, options: DevOptions, root: string): LocalServicesPlan {
  const project = options.project ?? composeProjectName(packageName(root));
  const described = describeInfrastructure(config as never);
  const taken = new Set<number>();
  const chosen = new Set(Object.values(options.services).flatMap((entry) => (entry.enabled !== false && entry.port !== undefined ? [entry.port] : [])));
  const services: LocalService[] = [];
  for (const service of described.services) {
    const setting = options.services[service.name];
    if (setting?.enabled === false) continue;
    const ports: Record<number, number> = {};
    service.ports.forEach((container, index) => {
      let host = index === 0 && setting?.port !== undefined ? setting.port : container;
      if (!(index === 0 && setting?.port !== undefined)) while (taken.has(host) || chosen.has(host)) host++;
      taken.add(host);
      ports[container] = host;
    });
    services.push({ name: service.name, kind: service.kind, image: setting?.image ?? service.image, ports, port: ports[service.ports[0]!]!, service });
  }
  const env = resolveInfraEnv(
    services.map((entry) => entry.service),
    Object.fromEntries(services.map((entry) => [entry.name, { host: "localhost", ports: entry.ports }])),
  );
  const token = "QSSECRETPLACEHOLDER";
  const maskedEnv = Object.fromEntries(
    Object.entries(
      resolveInfraEnv(
        services.map((entry) => entry.service),
        Object.fromEntries(services.map((entry) => [entry.name, { host: "localhost", ports: entry.ports, ...(entry.service.credentials.password ? { credentials: { password: token } } : {}) }])),
      ),
    ).map(([name, value]) => [name, value.split(token).join("[secret]")]),
  );
  return { project, file: options.composeFile, services, document: composeDocument(project, services, options), env, maskedEnv };
}

/** The compose document of the local services: image, ports, health check, variables and a named volume each. */
export function composeDocument(project: string, services: readonly LocalService[], options: Pick<DevOptions, "services">): ComposeDocument {
  const document: ComposeDocument = { name: project, services: {} };
  const volumes: Record<string, Record<string, unknown>> = {};
  for (const entry of services) {
    const { service } = entry;
    const environment = { ...service.environment, ...options.services[entry.name]?.env };
    const definition: Record<string, unknown> = {
      image: entry.image,
      ...(service.command ? { command: [...service.command] } : {}),
      ...(Object.keys(environment).length > 0 ? { environment } : {}),
      ports: Object.entries(entry.ports).map(([container, host]) => `${host}:${container}`),
      ...(service.health ? { healthcheck: { test: [...service.health], interval: "2s", timeout: "5s", retries: 30, start_period: "5s" } } : {}),
    };
    if (service.data) {
      const volume = `${entry.name}_data`;
      definition.volumes = [`${volume}:${service.data}`];
      volumes[volume] = { name: `${project}_${entry.name}_data` };
    }
    document.services[entry.name] = definition;
  }
  if (Object.keys(volumes).length > 0) document.volumes = volumes;
  return document;
}

const PLAIN = /^[A-Za-z0-9_./-]+$/;

/** A YAML scalar: plain when it cannot be misread, quoted otherwise. */
function scalar(value: unknown): string {
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  const text = String(value);
  return PLAIN.test(text) && !/^(true|false|null|yes|no|on|off|~|[0-9.]+)$/i.test(text) ? text : JSON.stringify(text);
}

/** A value as YAML lines at an indentation. */
function yamlLines(value: unknown, indent: number): string[] {
  const pad = " ".repeat(indent);
  if (Array.isArray(value)) {
    return value.flatMap((item) => (typeof item === "object" && item !== null ? [`${pad}-`, ...yamlLines(item, indent + 2)] : [`${pad}- ${scalar(item)}`]));
  }
  return Object.entries(value as Record<string, unknown>).flatMap(([key, item]) => {
    if (item === undefined) return [];
    if (typeof item === "object" && item !== null) {
      const empty = Array.isArray(item) ? item.length === 0 : Object.keys(item).length === 0;
      return empty ? [`${pad}${scalar(key)}: ${Array.isArray(item) ? "[]" : "{}"}`] : [`${pad}${scalar(key)}:`, ...yamlLines(item, indent + 2)];
    }
    return [`${pad}${scalar(key)}: ${scalar(item)}`];
  });
}

/** The text of a compose file: the generated header, then the document as YAML. */
export function composeYaml(document: ComposeDocument): string {
  return `${COMPOSE_HEADER}\n${yamlLines(document, 0).join("\n")}\n`;
}

/** Writes a file only when its content changed, so its modification time stays the same otherwise; true when written. */
export function writeWhenChanged(file: string, content: string): boolean {
  if (existsSync(file) && readFileSync(file, "utf8") === content) return false;
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  return true;
}
