/** The runtime images `dockerfile` writes, pinned. */
export const RUNTIME_IMAGES = { distroless: "gcr.io/distroless/cc-debian12", "bun-slim": "oven/bun:1.4.2-slim" } as const;

/** What `dockerfile` takes. */
export interface DockerfileOptions {
  /** The artifact copied into `/app`: a binary, or a folder like `server` for the bun-slim base. */
  artifact: string;
  /** The runtime stage's image: `distroless` for a compiled binary, `bun-slim` for a bundle (default `distroless`). */
  base?: keyof typeof RUNTIME_IMAGES;
  /** The non-root user id the service runs as (default 10001). */
  user?: number;
  /** The port the service listens on, set as `PORT` and exposed. */
  port: number;
  /** The command, as a list (default `["/app/<artifact>"]`). */
  entrypoint?: readonly string[];
  /** A stage that builds the artifact first, from the project's sources: its image and its commands. */
  buildStage?: { image?: string; commands: readonly string[]; output: string };
  /** A command the image runs as its `HEALTHCHECK`, as a list. */
  healthcheck?: readonly string[];
}

/**
 * The `Dockerfile` and `.dockerignore` that package the service as an image: a runtime stage on distroless (or Bun's
 * slim image) running as a non-root user, after an optional build stage, with an optional `HEALTHCHECK`. Every target
 * and generator that builds an image writes this same runtime stage.
 */
export function dockerfile(options: DockerfileOptions): { dockerfile: string; dockerignore: string } {
  const user = options.user ?? 10001;
  const base = RUNTIME_IMAGES[options.base ?? "distroless"];
  const entrypoint = options.entrypoint ?? [`/app/${options.artifact}`];
  const build = options.buildStage;
  const lines = [
    "# Generated by quickservicets build. Do not edit.",
    ...(build ? [`FROM ${build.image ?? "oven/bun:1.4.2"} AS build`, "WORKDIR /src", "COPY . .", ...build.commands.map((command) => `RUN ${command}`), ""] : []),
    `FROM ${base}`,
    "WORKDIR /app",
    build ? `COPY --from=build --chown=${user}:${user} /src/${build.output} /app/${options.artifact}` : `COPY --chown=${user}:${user} ${options.artifact} /app/${options.artifact}`,
    `USER ${user}:${user}`,
    `ENV PORT=${options.port}`,
    `EXPOSE ${options.port}`,
    ...(options.healthcheck ? [`HEALTHCHECK --interval=10s --timeout=3s --retries=3 CMD ${JSON.stringify(options.healthcheck)}`] : []),
    `ENTRYPOINT ${JSON.stringify(entrypoint)}`,
    "",
  ];
  const dockerignore = ["# Generated by quickservicets build. Do not edit.", "*", `!${options.artifact}`, ...(build ? ["!package.json", "!bun.lock", "!quickservicets.config.ts", "!entities", "!endpoints", "!hooks", "!jobs", "!features", "!migrations", "!.env.example"] : []), ""].join("\n");
  return { dockerfile: lines.join("\n"), dockerignore };
}
