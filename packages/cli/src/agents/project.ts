import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { SKILL_NAME, SKILL_RULES, skillMarkdown } from "./skill.ts";
import { readTopics, type AgentTopic } from "./topics.ts";

/** The first line of every agent file `init` writes (after the frontmatter of `SKILL.md`). */
export const GENERATED_HEADER = "<!-- generated by quickservicets; edit below the marker to keep your changes -->";

/** The line that ends the generated part of an agent file; what follows it is the developer's. */
export const END_MARKER = "<!-- quickservicets:end -->";

/** Where `init` puts the skill in a project. */
export const PROJECT_SKILL_DIR = `.claude/skills/${SKILL_NAME}`;

/** What the project's agent files say about it. */
export interface ProjectInfo {
  name: string;
  /** The database adapter: `postgres`, `mongodb`, `sqlite`, `memory`, or undefined when the config uses another. */
  database?: string;
  /** The project's `package.json` scripts. */
  scripts: Record<string, string>;
}

const DATABASE_NAMES: Record<string, string> = { postgres: "PostgreSQL", mongodb: "MongoDB", sqlite: "SQLite", memory: "the in-memory database" };

/** Reads the name, the database and the scripts of the project at `root`. */
export function projectInfo(root: string): ProjectInfo {
  const read = (file: string) => (existsSync(join(root, file)) ? readFileSync(join(root, file), "utf8") : "");
  let manifest: { name?: string; scripts?: Record<string, string> } = {};
  try {
    manifest = JSON.parse(read("package.json") || "{}");
  } catch {
    manifest = {};
  }
  const adapter = /\b(postgres|mongodb|sqlite|memory)Adapter\s*\(/.exec(read("quickservicets.config.ts"))?.[1];
  return { name: manifest.name ?? basename(root), ...(adapter ? { database: adapter } : {}), scripts: manifest.scripts ?? {} };
}

/** The lines of the project commands, as its `package.json` runs them. */
function commandLines(info: ProjectInfo): string[] {
  const script = (name: string, fallback: string, what: string) =>
    info.scripts[name] ? `- \`bun run ${name}\` (\`${info.scripts[name]}\`): ${what}` : `- \`${fallback}\`: ${what}`;
  const migrations = info.database !== "memory";
  return [
    script("dev", "bun run quickservicets dev", "builds, serves on port 3000 and rebuilds on every change."),
    script("build", "bun run quickservicets build", "writes `.generated/`; run it after every change to the sources."),
    ...(migrations
      ? [
          "- `bun run quickservicets migration add <Name>`: writes a migration from the model changes, like `bun run quickservicets migration add CreateTasks`.",
          script("migrate", "bun run quickservicets migrate", "applies the pending migrations."),
        ]
      : ["- No migrations: the in-memory database keeps no schema, and its data is lost when the service stops."]),
    "- `bun test`: runs the tests in `tests/` (use `startTestService` from `@quickservicets/cli/testing`).",
    ...(info.scripts.typecheck ? [script("typecheck", "", "type-checks the project; run `bun run build` first.")] : []),
    ...(info.scripts.start ? [script("start", "", "starts the last build, as in production.")] : []),
    "- `bun run quickservicets help`: lists every command.",
  ];
}

/** The project's `AGENTS.md`, with its marker. */
export function projectAgentsMarkdown(info: ProjectInfo, topics: readonly AgentTopic[] = readTopics()): string {
  const database = info.database ? DATABASE_NAMES[info.database]! : "the database set in `quickservicets.config.ts`";
  return [
    GENERATED_HEADER,
    "",
    `# ${info.name}`,
    "",
    `\`${info.name}\` is a QuickService.ts service on ${database}: its entities in \`entities/\` become REST routes, validation, migrations and OpenAPI docs, generated by \`quickservicets build\`.`,
    "",
    "## Commands",
    "",
    ...commandLines(info),
    "",
    "## Folders",
    "",
    "- `entities/`: one entity type per file, PascalCase (`entities/Task.ts` exports `Task`, served at `/tasks`).",
    "- `endpoints/`: custom routes, one file per route; the folders are the path and the file name is the method (`endpoints/tasks/[id]/complete/post.ts`).",
    "- `hooks/`: code that runs before or after routes, attached with a JSDoc tag named after the file (`hooks/authorized.ts` is `@authorized`).",
    "- `jobs/`: scheduled jobs, one file each, default-exporting `job(schedule, handler)`.",
    "- `features/`: the project's own features, one folder each, turned on by their key in the config.",
    ...(info.database === "memory" ? [] : ["- `migrations/`: written by `quickservicets migration add`; never edit them by hand."]),
    "- `.generated/`: written by `quickservicets build`; never edit it.",
    "",
    "## Rules",
    "",
    ...SKILL_RULES.map((rule) => `- ${rule}`),
    "",
    "## More",
    "",
    `- The agent guide topics are in \`${PROJECT_SKILL_DIR}/topics/\`: ${topics.map((topic) => `[${topic.name}](${PROJECT_SKILL_DIR}/topics/${topic.name}.md)`).join(", ")}.`,
    "- The docs site serves every page as Markdown for agents from [/llms.txt](/llms.txt).",
    "- After upgrading QuickService.ts, `bun run quickservicets agents update` refreshes these files above the marker.",
    "",
    END_MARKER,
    "",
  ].join("\n");
}

/** Puts the generated header after a `SKILL.md` frontmatter, or first, and the marker last. */
function marked(markdown: string): string {
  const body = markdown.replace(/\n+$/, "");
  const frontmatter = /^---\n[\s\S]*?\n---\n/.exec(body)?.[0];
  return frontmatter ? `${frontmatter}${GENERATED_HEADER}\n${body.slice(frontmatter.length)}\n\n${END_MARKER}\n` : `${GENERATED_HEADER}\n\n${body}\n\n${END_MARKER}\n`;
}

/** Every agent file of a project, keyed by its path in the project. */
export function projectAgentFiles(info: ProjectInfo, topics: readonly AgentTopic[] = readTopics()): Record<string, string> {
  return {
    "AGENTS.md": projectAgentsMarkdown(info, topics),
    "CLAUDE.md": `${GENERATED_HEADER}\n@AGENTS.md\n${END_MARKER}\n`,
    [`${PROJECT_SKILL_DIR}/SKILL.md`]: marked(skillMarkdown(topics)),
    ...Object.fromEntries(topics.map((topic) => [`${PROJECT_SKILL_DIR}/topics/${topic.name}.md`, marked(topic.markdown)])),
  };
}

/** Writes the agent files into a new project. */
export function writeProjectAgentFiles(root: string, info: ProjectInfo = projectInfo(root)): string[] {
  const files = projectAgentFiles(info);
  for (const [path, content] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), content);
  }
  return Object.keys(files);
}

/** What `quickservicets agents update` did. */
export interface AgentsUpdate {
  /** The files written: missing ones, and ones whose generated part changed. */
  changed: string[];
  /** The files without the marker, left alone. */
  skipped: string[];
}

/**
 * Rewrites the generated part (up to the end marker) of each agent file of the project at `root`, keeping what the
 * developer wrote below the marker; writes missing files and leaves files without the marker alone.
 */
export function updateProjectAgentFiles(root: string, info: ProjectInfo = projectInfo(root)): AgentsUpdate {
  const result: AgentsUpdate = { changed: [], skipped: [] };
  for (const [path, generated] of Object.entries(projectAgentFiles(info))) {
    const file = join(root, path);
    if (!existsSync(file)) {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, generated);
      result.changed.push(path);
      continue;
    }
    const current = readFileSync(file, "utf8");
    const end = current.indexOf(END_MARKER);
    if (end < 0) {
      result.skipped.push(path);
      continue;
    }
    const kept = current.slice(end + END_MARKER.length).replace(/^\n/, "");
    const next = `${generated}${kept}`;
    if (next === current) continue;
    writeFileSync(file, next);
    result.changed.push(path);
  }
  return result;
}
