import { describe, expect, test } from "bun:test";
import { readTopics, TOPIC_NAMES } from "../../packages/cli/src/agents/topics.ts";
import { pagesUnder } from "../scripts/checks.ts";
import { CONTENT_DIR, llmsFiles, llmsFull, llmsSmall, llmsTxt, markdownPathOf, pagePath, readPages, toPlainMarkdown, unrenderedLines } from "../scripts/llms.ts";

const topics = readTopics();
const pages = readPages();

describe("llms.txt", () => {
  const text = llmsTxt(topics, pages);

  test("has the H1, a blockquote summary, a paragraph on when to use it, then the five sections", () => {
    const lines = text.split("\n");
    expect(lines[0]).toBe("# QuickService.ts");
    expect(lines[2]).toStartWith("> QuickService.ts builds REST services on Bun");
    expect(lines[4]).toStartWith("Use it for ");
    expect(lines.filter((line) => line.startsWith("## "))).toEqual(["## Agent guides", "## Getting started", "## Guides", "## Reference", "## Recipes"]);
  });

  test("lists every agent topic and every page as - [Title](<url>.md): <description>", () => {
    for (const topic of topics) expect(text).toContain(`- [${topic.title}](/agents/${topic.name}.md): ${topic.summary}\n`);
    expect(pages.map((page) => page.file).sort()).toEqual(pagesUnder(CONTENT_DIR));
    for (const page of pages) {
      expect(page.description).not.toBe("");
      expect(text).toContain(`- [${page.title}](${page.markdownPath}): ${page.description}\n`);
    }
    expect(text).toContain("- [Queues](/guides/queues.md): ");
  });

  test("pages are in sidebar order, the tutorial and the home page under Getting started", () => {
    const section = (name: string) => text.split(`## ${name}\n\n`)[1]!.split("\n\n")[0]!.split("\n");
    expect(section("Getting started").slice(0, 3).map((line) => line.split(":")[0])).toEqual([
      "- [QuickService.ts](/index.md)",
      "- [Introduction](/getting-started.md)",
      "- [Installation and init](/getting-started/installation.md)",
    ]);
    expect(section("Getting started").some((line) => line.includes("(/tutorial/testing.md)"))).toBe(true);
    expect(section("Guides")[0]).toStartWith("- [Entities and tags](/guides/entities.md)");
    expect(section("Guides").at(-1)).toStartWith("- [Guides](/guides.md)");
    expect(section("Reference")[0]).toStartWith("- [Reference](/reference.md)");
  });
});

describe("MDX to Markdown", () => {
  test("tables and code blocks stay, the check marker goes", () => {
    const body = ["| A | B |", "| --- | --- |", "| 1 | 2 |", "", '```ts check title="entities/User.ts"', "import type { Post } from \"./Post\";", "export type User = { posts: Post[] };", "```"].join("\n");
    expect(toPlainMarkdown(body)).toBe(["| A | B |", "| --- | --- |", "| 1 | 2 |", "", '```ts title="entities/User.ts"', 'import type { Post } from "./Post";', "export type User = { posts: Post[] };", "```"].join("\n"));
  });

  test("admonitions become blockquotes, with their code", () => {
    const body = [":::tip", "You can also build:", "", "```bash", "bun run build", "```", ":::", "", ":::caution[Careful]", "Placeholders.", ":::"].join("\n");
    expect(toPlainMarkdown(body)).toBe(["> **Tip:**", ">", "> You can also build:", ">", "> ```bash", "> bun run build", "> ```", "", "> **Careful:**", ">", "> Placeholders."].join("\n"));
  });

  test("import lines, comments and components go; a component's title stays as a bold line", () => {
    const body = [
      'import { Card, CardGrid } from "@astrojs/starlight/components";',
      "",
      "{/* Generated by `bun run docs:reference`. Do not edit by hand. */}",
      "<!-- Generated. -->",
      "",
      "<CardGrid>",
      '  <Card title="Entities as types" icon="document">',
      "    Plain `type` declarations.",
      "  </Card>",
      "</CardGrid>",
      "",
      "Text with `Endpoint<Body, Result>`.",
    ].join("\n");
    expect(toPlainMarkdown(body)).toBe(["**Entities as types**", "Plain `type` declarations.", "", "Text with `Endpoint<Body, Result>`."].join("\n"));
  });

  test("the check finds import lines and component tags outside code, not inside code or inline code", () => {
    expect(unrenderedLines(['import { Card } from "x";', "<Card title=\"A\">", "`<Entity> not found`", "```ts", 'import { a } from "b";', "```"].join("\n"))).toEqual([
      '1: import { Card } from "x";',
      '2: <Card title="A">',
    ]);
  });
});

describe("llms-full.txt and llms-small.txt", () => {
  test("llms-full.txt starts with the agent topics, then every page under its title and URL, with no import line or component", () => {
    const full = llmsFull(topics, pages);
    expect(full).toStartWith("# Overview\n\nURL: /agents/overview.md\n\nWhat QuickService.ts is");
    const titles = full.split("\n").filter((line, index, lines) => line.startsWith("# ") && lines[index + 2]?.startsWith("URL: "));
    expect(titles.length).toBe(TOPIC_NAMES.length + pages.length);
    expect(full).toContain("# Queues\n\nURL: /guides/queues.md\n");
    expect(unrenderedLines(full)).toEqual([]);
  });

  test("llms-small.txt holds the topics, the getting started pages and the CLI, config and tags reference, under 200 KB", () => {
    const small = llmsSmall(topics, pages);
    const urls = small.split("\n").filter((line) => line.startsWith("URL: ")).map((line) => line.slice(5));
    expect(urls).toEqual([
      ...TOPIC_NAMES.map((name) => `/agents/${name}.md`),
      ...pages.filter((page) => page.file.startsWith("getting-started/")).map((page) => page.markdownPath),
      "/reference/cli.md",
      "/reference/config.md",
      "/reference/tags.md",
    ]);
    expect(new TextEncoder().encode(small).length).toBeLessThan(200 * 1024);
  });
});

describe("Markdown copies of the pages", () => {
  test("every page and topic has a .md route next to its path", () => {
    expect(pagePath("guides/queues.md")).toBe("/guides/queues/");
    expect(pagePath("guides/index.md")).toBe("/guides/");
    expect(pagePath("index.mdx")).toBe("/");
    expect(markdownPathOf("/guides/queues/")).toBe("/guides/queues.md");
    expect(markdownPathOf("/")).toBe("/index.md");
    const files = llmsFiles(topics, pages);
    expect(Object.keys(files).filter((path) => path.endsWith(".md")).length).toBe(TOPIC_NAMES.length + pages.length);
    expect(files["guides/queues.md"]).toStartWith("# Queues\n\n> ");
    expect(files["agents/quickstart.md"]).toContain("Full docs: [Getting started](/getting-started/installation.md)");
  });
});
