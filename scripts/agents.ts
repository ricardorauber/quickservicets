/** The version the packages share, read from the unscoped package. */
const packagesVersion = (root: string) => (JSON.parse(readFileSync(join(root, "packages/quickservicets/package.json"), "utf8")) as { version: string }).version;

/** Every file this script writes, keyed by its path in the repository. */
export function generatedFiles(root: string = ROOT, topics: readonly AgentTopic[] = readTopics(join(root, "packages/cli/agent-docs"))): Record<string, string> {
  const version = packagesVersion(root);
  return {
    "AGENTS.md": agentsMarkdown(topics, root),
    [`${SKILL_DIR}/SKILL.md`]: skillMarkdown(topics),
    ...Object.fromEntries(topics.map((topic) => [`${SKILL_DIR}/topics/${topic.name}.md`, topic.markdown])),
    ".claude-plugin/plugin.json": json(pluginManifest(version)),
    ".claude-plugin/marketplace.json": json(marketplaceManifest(version)),
    ...Object.fromEntries(readPages(join(root, CONTENT)).map((page) => [`${DOCS_PAGES}/${page.markdownPath.slice(1)}`, pageMarkdown(page)])),
  };
}

/** The generated files that are missing or differ from the files under `root`. */
export function staleFiles(files: Record<string, string>, root: string = ROOT): string[] {
  return Object.entries(files)
    .filter(([path, content]) => {
      try {
        return readFileSync(join(root, path), "utf8") !== content;
      } catch {
        return true;
      }
    })
    .map(([path]) => path);
}

/** What the topics may mention: commands, config keys, `QS_*` variables and tags. */
export interface KnownNames {
  commands: readonly (readonly string[])[];
  configPaths: readonly string[];
  variables: ReadonlySet<string>;
  tags: ReadonlySet<string>;
}

/** The commands, config keys, variables and tags of the CLI registry, the option schemas and the tag registries. */
export function knownNames(): KnownNames {
  const natives = registeredNatives();
  const commands = [...BUILT_IN_COMMANDS, ...natives.flatMap((native) => native.commands ?? [])].map((command) => command.words);
  const configPaths = [
    ...configKeys().map((key) => key.path),
    ...natives.flatMap((native) => [native.key, ...describeOptions(native.schema, native.key).map((option) => option.path)]),
  ];
  const tags = [
    ...[...documentedEntityTags(), ...documentedFieldTags(), ...documentedEndpointTags()].map((tag) => tag.name),
    ...natives.flatMap((native) => Object.keys(native.tags ?? {})),
  ];
  return {
    commands: [...commands, ...RESERVED_COMMANDS.map((name) => [name])],
    configPaths,
    variables: new Set(overrideVariables(natives).keys()),
    tags: new Set(tags),
  };
}

const COMMAND_MENTION = /(?<![\w@/.-])quickservicets((?: [a-z][a-z0-9-]*)+)/g;
const VARIABLE_MENTION = /\bQS_[A-Z0-9_]*[A-Z0-9]\b/g;
const TAG_MENTION = /(?<![\w"'@/.-])@([a-zA-Z][a-zA-Z0-9]*)(?![\w/.-])/g;
const CONFIG_PATH = /^[a-z][A-Za-z0-9]*(?:\.[A-Za-z][A-Za-z0-9]*)+$/;
const HOOK_FILE = /\bhooks\/([a-z][a-zA-Z0-9]*)\.ts\b/g;

/** Whether `words` name a command, or the words of a group of commands (like `migration`). */
const isCommand = (words: readonly string[], commands: KnownNames["commands"]) =>
  commands.some(
    (command) => command.every((word, index) => words[index] === word) || words.every((word, index) => command[index] === word),
  );

/** Whether `path` is a config key or the start of one; `<name>` segments of record options match any name. */
function isConfigPath(path: string, known: readonly string[]): boolean {
  const segments = path.split(".");
  return known.some((candidate) => {
    const parts = candidate.split(".");
    return parts.length >= segments.length && segments.every((segment, index) => parts[index] === segment || /^<.+>$/.test(parts[index]!));
  });
}

/**
 * Every command, config key, `QS_*` variable and tag the topics mention that does not exist, as
 * `<topic>.md:<line>: <what>`. Config keys are the dotted names in inline code whose first segment is a config key;
 * tags may also name the hooks the topics write in `hooks/<name>.ts`.
 */
export function unknownMentions(topics: readonly Pick<AgentTopic, "name" | "markdown">[], known: KnownNames = knownNames()): string[] {
  const hooks = new Set(topics.flatMap((topic) => [...topic.markdown.matchAll(HOOK_FILE)].map((match) => match[1]!)));
  const roots = new Set(known.configPaths.map((path) => path.split(".")[0]!));
  const problems: string[] = [];
  for (const topic of topics) {
    let fenced = false;
    topic.markdown.split("\n").forEach((line, index) => {
      const at = `${topic.name}.md:${index + 1}`;
      if (/^\s*(```|~~~)/.test(line)) fenced = !fenced;
      for (const match of line.matchAll(COMMAND_MENTION)) {
        const words = match[1]!.trim().split(" ");
        if (!isCommand(words, known.commands)) problems.push(`${at}: unknown command "quickservicets ${words.join(" ")}"`);
      }
      for (const match of line.matchAll(VARIABLE_MENTION)) {
        if (!known.variables.has(match[0])) problems.push(`${at}: unknown variable ${match[0]}`);
      }
      for (const match of line.matchAll(TAG_MENTION)) {
        if (!known.tags.has(match[1]!) && !hooks.has(match[1]!)) problems.push(`${at}: unknown tag @${match[1]}`);
      }
      if (fenced) return;
      for (const match of line.matchAll(/`([^`]+)`/g)) {
        const path = match[1]!;
        if (CONFIG_PATH.test(path) && roots.has(path.split(".")[0]!) && !isConfigPath(path, known.configPaths)) problems.push(`${at}: unknown config key ${path}`);
      }
    });
  }
  return problems;
}

/** Writes every generated file under `root` that is missing or differs, returning `Wrote <path>` or `Unchanged <path>` per file. */
export function writeGenerated(root: string = ROOT, files: Record<string, string> = generatedFiles(root)): string[] {
  return Object.entries(files).map(([path, content]) => {
    const file = join(root, path);
    const changed = !existsSync(file) || readFileSync(file, "utf8") !== content;
    if (changed) {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, content);
    }
    return `${changed ? "Wrote" : "Unchanged"} ${path}`;
  });
}

