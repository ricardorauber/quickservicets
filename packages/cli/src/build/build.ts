import {
  entityRoutePath,
  loadConfig,
  parseFieldPaths,
  type Projection,
  operationForRoute,
  resolveRouteHooks,
  type CrudRouteEntry,
  type EntityModel,
  type HookCall,
} from "@quickservice/core";
import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseEntities } from "../entities/parse-entities.ts";
import { BuildError } from "../errors.ts";
import { scanEndpoints, type EndpointRoute } from "../endpoints/scan-endpoints.ts";
import { parseEndpointTags, type EndpointMetadata } from "../hooks/endpoint-tags.ts";
import { scanHooks, type HookEntry } from "../hooks/scan-hooks.ts";
import { validateHookReferences } from "../hooks/validate-hook-references.ts";
import { hasPendingChanges, sqlDialectOf } from "../migrations/add.ts";
import { generateTypesFile } from "./generate-types.ts";

export const GENERATED_DIR = ".generated";

export interface BuildSummary {
  entities: number;
  endpoints: number;
  hooks: number;
  warnings: string[];
}

export const PENDING_MIGRATION_WARNING =
  'Model has changes without a migration. Run "quickservice migration add <Name>"';

interface ResolvedEndpoint {
  route: EndpointRoute;
  hooks: HookCall[];
  projection?: Projection;
}

interface ScannedEndpoint {
  route: EndpointRoute;
  hooks: HookCall[];
  metadata: EndpointMetadata;
}

const HEADER = "// Generated by quickservice build. Do not edit.";
const CRUD_ROUTES: [string, string, CrudRouteEntry["operation"]][] = [
  ["GET", "", "list"],
  ["GET", "/[id]", "read"],
  ["POST", "", "create"],
  ["PATCH", "/[id]", "update"],
  ["PUT", "/[id]", "replace"],
  ["DELETE", "/[id]", "delete"],
];

function crudTable(models: EntityModel[]): CrudRouteEntry[] {
  return models
    .filter((model) => !model.internal)
    .flatMap((model) =>
      CRUD_ROUTES.map(([method, suffix, operation]) => ({
        method,
        path: `${entityRoutePath(model)}${suffix}`,
        entity: model.key,
        operation,
        hooks: resolveRouteHooks({ kind: "generated", entity: model, operation }),
      })),
    );
}

function overriddenRoute(route: EndpointRoute, models: EntityModel[]) {
  for (const entity of models) {
    if (entity.internal) continue;
    const operation = operationForRoute(entity, route.method, route.pattern);
    if (operation) return { entity, operation };
  }
  return undefined;
}

function resolveEndpoint(endpoint: ScannedEndpoint, models: EntityModel[]): ResolvedEndpoint {
  const { route, metadata } = endpoint;
  const override = overriddenRoute(route, models);
  if (!override) {
    return { route, hooks: resolveRouteHooks({ kind: "custom", endpointHooks: endpoint.hooks }), projection: metadata.projection };
  }
  const { entity, operation } = override;
  const hooks = resolveRouteHooks({ kind: "override", entity, operation, endpointHooks: endpoint.hooks });
  if (operation !== "list" && operation !== "read") return { route, hooks, projection: metadata.projection };
  if (!metadata.projection) return { route, hooks, projection: entity.exposure[operation] };
  const paths = [...(metadata.projection.include ?? []), ...(metadata.projection.exclude ?? [])];
  const parsed = parseFieldPaths(entity, paths);
  if (!parsed.ok) throw new BuildError(`${route.file}: unknown path ${parsed.invalid.join(", ")} in @fields/@exclude`);
  return { route, hooks, projection: metadata.projection };
}

function generateRoutesFile(
  models: EntityModel[],
  endpoints: ResolvedEndpoint[],
  hooks: Map<string, HookEntry>,
): string {
  const hookNames = [...hooks.keys()].sort();
  const imports = [
    'import type { AppEndpoint, CrudRouteEntry, Endpoint, HookDefinition } from "@quickservice/core";',
    ...endpoints.map((endpoint, index) => `import endpoint${index} from ${JSON.stringify(`../${endpoint.route.file}`)};`),
    ...hookNames.map((name) => `import hook_${name} from ${JSON.stringify(`../${hooks.get(name)!.file}`)};`),
  ];
  const endpointEntries = endpoints.map(
    (endpoint, index) =>
      `  { method: ${JSON.stringify(endpoint.route.method)}, path: ${JSON.stringify(endpoint.route.path)}, hooks: ${JSON.stringify(endpoint.hooks)}, ${endpoint.projection ? `projection: ${JSON.stringify(endpoint.projection)}, ` : ""}handler: endpoint${index} as Endpoint },`,
  );
  return [
    HEADER,
    ...imports,
    "",
    `export const crudRoutes: CrudRouteEntry[] = ${JSON.stringify(crudTable(models), null, 2)};`,
    "",
    "export const endpoints: AppEndpoint[] = [",
    ...endpointEntries,
    "];",
    "",
    "export const hooks = new Map<string, HookDefinition>([",
    ...hookNames.map((name) => `  [${JSON.stringify(name)}, hook_${name}],`),
    "]);",
    "",
  ].join("\n");
}

const SERVER_FILE = `${HEADER}
import { createApp, resolveConfig } from "@quickservice/core";
import projectConfig from "../quickservice.config.ts";
import { models } from "./models.ts";
import { crudRoutes, endpoints, hooks } from "./routes.ts";

const config = resolveConfig(projectConfig);
await config.database.connect(models, { defaultSchema: config.schema });
const { server } = createApp({ models, crudRoutes, endpoints, hooks, config });
const listening = server.listen();
console.log(\`quickservice listening on http://localhost:\${listening.port}\`);
`;

/** Builds the project at `projectRoot` into `.generated/`, replacing the previous output only on success. */
export async function build(projectRoot: string): Promise<BuildSummary> {
  const config = await loadConfig(projectRoot);
  const models = parseEntities(projectRoot);
  const hooks = await scanHooks(projectRoot);
  const endpoints: ScannedEndpoint[] = scanEndpoints(projectRoot).map((route) => ({
    route,
    ...parseEndpointTags(readFileSync(join(projectRoot, route.file), "utf8"), route.file),
  }));
  validateHookReferences(
    models,
    endpoints.map((endpoint) => ({ file: endpoint.route.file, hooks: endpoint.hooks })),
    hooks,
  );
  const resolved = endpoints.map((endpoint) => resolveEndpoint(endpoint, models));

  const files: Record<string, string> = {
    "models.ts": `${HEADER}\nimport type { EntityModel } from "@quickservice/core";\n\nexport const models: EntityModel[] = ${JSON.stringify(models, null, 2)};\n`,
    "types.ts": generateTypesFile(models),
    "routes.ts": generateRoutesFile(models, resolved, hooks),
    "server.ts": SERVER_FILE,
  };

  const target = join(projectRoot, GENERATED_DIR);
  const staging = join(projectRoot, `${GENERATED_DIR}.staging`);
  rmSync(staging, { recursive: true, force: true });
  mkdirSync(staging, { recursive: true });
  for (const [name, content] of Object.entries(files)) writeFileSync(join(staging, name), content);
  if (existsSync(target)) rmSync(target, { recursive: true, force: true });
  renameSync(staging, target);

  const warnings: string[] = [];
  const dialect = sqlDialectOf(config.database.kind);
  if (dialect && (await hasPendingChanges(projectRoot, models, dialect))) warnings.push(PENDING_MIGRATION_WARNING);
  return { entities: models.length, endpoints: endpoints.length, hooks: hooks.size, warnings };
}
