/** The queues of the `queues` feature's folder, with how `.generated/types.ts` imports each file. */
function queueTypes(files: readonly FolderFile[]): QueueTypeEntry[] {
  return files.filter((entry) => entry.feature === "queues" && entry.folder === "queues").map((entry) => ({ name: entry.name, specifier: importPath(entry.file) }));
}

/** The queues entities publish to, with the write event types each receives. */
function publishedQueues(targets: readonly PublishTarget[]): PublishedQueueEntry[] {
  const byQueue = new Map<string, string[]>();
  for (const { entity, queue, events } of targets) {
    const types = byQueue.get(queue) ?? [];
    for (const operation of events) types.push(`${entity.entityName.charAt(0).toLowerCase()}${entity.entityName.slice(1)}.${operation}`);
    byQueue.set(queue, types);
  }
  return [...byQueue].map(([name, types]) => ({ name, types: [...new Set(types)] }));
}

/** On MongoDB and memory, unpaired reference arrays are embedded, so their `@joinTable` has no effect. */
export function joinTableWarnings(models: EntityModel[], kind: string | undefined): string[] {
  if (kind !== "mongodb" && kind !== "memory") return [];
  return models.flatMap((model) =>
    model.fields
      .filter((field) => field.type === "refArray" && field.storage === "relation" && field.joinTable)
      .map((field) => `entities/${model.key}.ts: @joinTable on field "${field.name}" is ignored on ${kind} (reference arrays are embedded)`),
  );
}

export const HNSW_ONLY_ON_POSTGRES = "@vector index=hnsw is used only on PostgreSQL";

/** One warning when a vector field asks for an HNSW index on a database that does not build one. */
export function vectorIndexWarnings(models: EntityModel[], kind: string | undefined): string[] {
  if (kind === "postgres") return [];
  return models.some((model) => model.fields.some((field) => field.vector?.index === "hnsw")) ? [HNSW_ONLY_ON_POSTGRES] : [];
}

/** Builds the project at `projectRoot` into `.generated/`, replacing the previous output only on success. */
/** What `build` accepts besides the project and the environment. */
export interface BuildOptions {
  /** Runs only these features' build steps, keeping the other features' output (default: every step). */
  steps?: readonly string[];
}

export async function build(projectRoot: string, env: Record<string, string | undefined> = process.env, options: BuildOptions = {}): Promise<BuildSummary> {
  assertFeatureImports(projectRoot);
  const config = await loadConfig(projectRoot, env);
  // Endpoint files are parsed with the enabled features' tags too.
  const restore = useFeatureTags(config.features, builtInTagOwner);
  try {
    return await buildProject(projectRoot, config, options);
  } finally {
    restore();
  }
}

async function buildProject(projectRoot: string, config: ResolvedConfig, options: BuildOptions): Promise<BuildSummary> {
  const featureKeys = registeredProjectFeatures().map((feature) => feature.key);
  const variables = declaredVariables(config.env, config.features.map((feature) => ({ key: feature.key, env: feature.definition.env })));
  const parsed = parseProjectModels(projectRoot, config.features);
  const overrides = [...replacedNatives().map(overrideLine), ...parsed.overrides];
  const models = parsed.models;
  const scanned = await scanProjectFiles(projectRoot, config.features);
  overrides.push(...scanned.overrides);
  const { hooks, jobs } = scanned;
  const folderFiles = await scanFeatureFolders(projectRoot, config.features, overrides);
  const publishing = publishTargets(models, config.features);
  const queueNames = new Set(queueTypes(folderFiles).map((entry) => entry.name));
  const publishWarnings = [...publishProblems(publishing, queueNames), ...overrideWarnings(config.features, queueNames, publishing)];
  assertNoHookConflicts(activeFeatureTags(), hooks);
  const endpoints: ScannedEndpoint[] = scanned.endpoints.map((route) => {
    const source = readFileSync(route.source ?? join(projectRoot, route.file), "utf8");
    if (route.kind === "sse") {
      if (!sseEnabled(config)) throw new BuildError(`${route.file} needs realtime: {} in quickservicets.config.ts`);
      assertSseExport(source, route.file);
    }
    return { route, ...parseEndpointTags(source, route.file) };
  });
  validateHookReferences(
    models,
    endpoints.map((endpoint) => ({ file: endpoint.route.file, hooks: endpoint.hooks })),
    hooks,
  );
  assertEntityPopulateDepth(models, config.populate.maxDepth);
  for (const model of models) {
    if (model.storageName && !(model.storageName in config.storage)) {
      throw new BuildError(`entities/${model.key}.ts: entity ${model.entityName} uses storage "${model.storageName}", which is not in the config`);
    }
    const [accessError] = model.file ? fileAccessErrors(model, config) : [];
    if (accessError) throw new BuildError(`entities/${model.key}.ts: ${accessError}`);
  }
  assertNoDocsConflicts(models, endpoints.map((endpoint) => endpoint.route));
  const queryItems = extractQueryItems(projectRoot, endpoints.map((endpoint) => endpoint.route));
  const resolved = endpoints.map((endpoint): ResolvedEndpoint => {
    const result = resolveEndpoint(endpoint, models, config.populate.maxDepth);
    const query = queryItems.get(endpoint.route.file);
    const { status, tags } = endpoint.metadata;
    return { ...result, ...(query ? { query } : {}), ...(status !== undefined ? { status } : {}), ...(tags ? { tags } : {}) };
  });
  const endpointDocs = describeEndpoints(
    projectRoot,
    models,
    resolved.map((endpoint, index) => ({
      route: endpoint.route,
      metadata: endpoints[index]!.metadata,
      override: endpoint.override,
      hooks: endpoint.hooks,
      query: endpoint.query,
    })),
  );
  const packageFile = join(projectRoot, "package.json");
  const packageJson = existsSync(packageFile) ? (JSON.parse(readFileSync(packageFile, "utf8")) as { name?: string; version?: string }) : {};
  const generatedOpenApi = generateOpenApi({
    models,
    routes: crudTable(models),
    hooks,
    packageJson,
    endpoints: endpointDocs.docs,
    files: config,
    populateMaxDepth: config.populate.maxDepth,
  });
  let openApi: OpenApiDoc;
  try {
    openApi = extendOpenApi(generatedOpenApi as unknown as OpenApiDoc, { features: config.features, config, models, routes: taggedBuildRoutes(models, resolved) });
  } catch (error) {
    throw new BuildError((error as Error).message);
  }

  const files: Record<string, string> = {
    "models.ts": `${HEADER}\nimport type { EntityModel } from "@quickservicets/core";\n\nexport const models: EntityModel[] = ${JSON.stringify(models, null, 2)};\n`,
    "types.ts": [generateTypesFile(models, envVarsLines(variables)), ...featureTypeLines(featureKeys), ...queuePayloadLines(queueTypes(folderFiles), publishedQueues(publishing))].join("\n"),
    "features.ts": generateFeaturesFile(HEADER, featureKeys, folderFiles.map((entry) => ({ ...entry, specifier: importPath(entry.file) }))),
    "routes.ts": generateRoutesFile(models, resolved, hooks),
    "jobs.ts": generateJobsFile(jobs),
    "server.ts": SERVER_FILE,
    "openapi.json": `${JSON.stringify(openApi, null, 2)}\n`,
  };

  // Build steps own `.generated/<key>/` of their enabled feature; the folders of other features are removed.
  const stepKeys = config.features.filter((feature) => feature.definition.build).map((feature) => feature.key);
  writeGeneratedFiles(join(projectRoot, GENERATED_DIR), files, stepKeys);
  // Earlier versions wrote through a staging folder.
  rmSync(join(projectRoot, `${GENERATED_DIR}.staging`), { recursive: true, force: true });

  const buildSteps = await runBuildSteps({ root: projectRoot, generatedDir: join(projectRoot, GENERATED_DIR), config, models, folderFiles, only: options.steps });
  const envExampleWarning = writeEnvExample(projectRoot, variables);
  const warnings: string[] = [...config.warnings, ...publishWarnings, ...(envExampleWarning ? [envExampleWarning] : []), ...joinTableWarnings(models, config.database.kind), ...vectorIndexWarnings(models, config.database.kind)];
  const tsconfigWarning = generatedIncludeWarning(projectRoot);
  if (tsconfigWarning) warnings.push(tsconfigWarning);
  warnings.push(...endpointDocs.warnings);
  const dialect = sqlDialectOf(config.database.kind);
  if (dialect && (await hasPendingChanges(projectRoot, models, dialect))) warnings.push(PENDING_MIGRATION_WARNING);
  return { entities: models.length, endpoints: endpoints.length, hooks: hooks.size, features: featureKeys.length, overrides, fromFeatures: scanned.fromFeatures, watch: featureWatchPaths(config.features), buildInputs: Object.fromEntries(config.features.filter((feature) => feature.definition.build).map((feature) => [feature.key, featureWatchPaths([feature])])), buildSteps, warnings };
}
