import type { EntityModel, FieldModel, NestedFieldModel, TypeDescriptor } from "@quickservice/core";

function typeOf(descriptor: TypeDescriptor, indent: string): string {
  switch (descriptor.type) {
    case "string":
    case "ref":
      return "string";
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "date":
      return "Date";
    case "enum":
      return descriptor.values.map((value) => JSON.stringify(value)).join(" | ");
    case "array":
      return `Array<${typeOf(descriptor.items, indent)}>`;
    case "refArray":
      return "Array<string>";
    case "object":
      return objectType(descriptor.fields, indent);
  }
}

function property(field: NestedFieldModel, optional: boolean, indent: string): string {
  const type = typeOf(field, indent);
  return optional ? `${indent}${field.name}?: ${type} | null;` : `${indent}${field.name}: ${type};`;
}

function objectType(fields: NestedFieldModel[], indent: string): string {
  const inner = `${indent}  `;
  return `{\n${fields.map((field) => property(field, field.optional, inner)).join("\n")}\n${indent}}`;
}

const pascalCase = (value: string) =>
  value.replace(/(^|-)([a-z0-9])/g, (_, __, char: string) => char.toUpperCase());

/** Type name of an entity; schema-bound entities sharing a type name with another schema get the schema prefix. */
export function entityTypeName(model: EntityModel, models: EntityModel[] = [model]): string {
  const shared = models.some((other) => other !== model && other.entityName === model.entityName);
  return shared && model.schema ? `${pascalCase(model.schema)}${model.entityName}` : model.entityName;
}

export function generateEntityType(model: EntityModel, models: EntityModel[] = [model]): string {
  // Reference arrays are always returned, as [] when empty.
  const fields = model.fields.map((field: FieldModel) =>
    property(field, field.type !== "refArray" && (field.optional || field.hidden === true), "  "),
  );
  return [
    `export type ${entityTypeName(model, models)} = {`,
    "  id: string;",
    "  createdAt: Date;",
    "  updatedAt: Date;",
    ...fields,
    "};",
  ].join("\n");
}

/** Maps reference fields to their referenced record types, so populated reads are typed. */
function referenceMap(model: EntityModel, models: EntityModel[]): string {
  const entries = model.fields.flatMap((field) => {
    if (field.type !== "ref") return [];
    const target = models.find((candidate) => candidate.key === field.target);
    return target ? [`${field.name}: ${entityTypeName(target, models)}`] : [];
  });
  return entries.length > 0 ? `, { ${entries.join("; ")} }` : "";
}

function repositoryLines(models: EntityModel[]): string[] {
  const line = (model: EntityModel, indent: string) =>
    `${indent}${model.repoKey}: Repository<${entityTypeName(model, models)}${referenceMap(model, models)}>;`;
  const lines = models.filter((model) => !model.schemaKey).map((model) => line(model, "  "));
  const schemaKeys = [...new Set(models.flatMap((model) => (model.schemaKey ? [model.schemaKey] : [])))];
  for (const schemaKey of schemaKeys) {
    lines.push(`  ${schemaKey}: {`);
    lines.push(...models.filter((model) => model.schemaKey === schemaKey).map((model) => line(model, "    ")));
    lines.push("  };");
  }
  return lines;
}

export function generateTypesFile(models: EntityModel[]): string {
  const repositories = repositoryLines(models);
  return [
    "// Generated by quickservice build. Do not edit.",
    'import type { Repository } from "@quickservice/core";',
    "",
    ...models.flatMap((model) => [generateEntityType(model, models), ""]),
    "export interface GeneratedRepositories {",
    ...repositories,
    "}",
    "",
    'declare module "@quickservice/core" {',
    "  interface Repositories extends GeneratedRepositories {}",
    "}",
    "",
  ].join("\n");
}
