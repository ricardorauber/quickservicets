export interface ConfigKey {
  path: string;
  type: string;
  description?: string;
  defaultValue?: string;
}

/** Every key of `ServiceConfig`, nested ones included, with its type, doc comment and documented default. */
export function configKeys(): ConfigKey[] {
  const file = join(REPO, "packages/core/src/config.ts");
  const source = ts.createSourceFile(file, readFileSync(file, "utf8"), ts.ScriptTarget.ESNext, true);
  const config = source.statements.find((statement): statement is ts.InterfaceDeclaration => ts.isInterfaceDeclaration(statement) && statement.name.text === "ServiceConfig");
  if (!config) throw new Error("ServiceConfig not found");
  const keys: ConfigKey[] = [];
  const visit = (members: ts.NodeArray<ts.TypeElement>, prefix: string) => {
    for (const member of members) {
      if (!ts.isPropertySignature(member) || !member.type) continue;
      const path = `${prefix}${member.name.getText(source)}`;
      const doc = ts
        .getJSDocCommentsAndTags(member)
        .filter(ts.isJSDoc)
        .map((comment) => ts.getTextOfJSDocComment(comment.comment) ?? "")
        .join(" ")
        .trim();
      const defaultValue = /\(default:? ([^)]*)\)/.exec(doc)?.[1] ?? /defaults to ([^.;]*)/.exec(doc)?.[1];
      const nested = ts.isTypeLiteralNode(member.type) ? member.type : undefined;
      keys.push({
        path,
        type: nested ? "object" : member.type.getText(source).replace(/\s+/g, " "),
        ...(doc ? { description: doc } : {}),
        ...(defaultValue ? { defaultValue: defaultValue.trim() } : {}),
      });
      if (nested) visit(nested.members, `${path}.`);
    }
  };
  visit(config.members, "");
  return keys;
}

const code = (text: string) => `\`${text.replaceAll("|", "\\|")}\``;
const frontmatter = (title: string, description: string) => `---\ntitle: ${title}\ndescription: ${description}\n---\n\n${HEADER}\n`;

function tagSection(tag: DocumentedTag): string {
  return [
    `### \`@${tag.name}\``,
    "",
    tag.description ?? "",
    "",
    `**Applies to:** ${tag.appliesTo ?? ""}`,
    "",
    "```ts",
    tag.example ?? "",
    "```",
    "",
  ].join("\n");
}

function tagsPage(): string {
  const groups: [string, string, DocumentedTag[]][] = [
    ["Entity tags", "Written in the JSDoc comment above an entity type. Any other tag on an entity names a hook from `hooks/`.", documentedEntityTags()],
    ["Field tags", "Written in the JSDoc comment above a field of an entity.", documentedFieldTags()],
    ["Endpoint tags", "Written in the JSDoc comment above an endpoint's default export. Any other tag names a hook from `hooks/`.", documentedEndpointTags()],
  ];
  return [
    frontmatter("JSDoc tags", "Every built-in tag for entities, fields and endpoints."),
    "Tags configure entities, fields and endpoints. This page lists every built-in tag; it is generated from the framework's tag registries.",
    "",
    ...groups.flatMap(([title, intro, tags]) => [`## ${title}`, "", intro, "", ...tags.map(tagSection)]),
  ].join("\n");
}

/** The environment variable column of a config key: its `QS_*` name and alias, `not overridable`, or empty for objects. */
function variableOf(key: ConfigKey): string {
  const root = key.path.split(".")[0]!;
  if (NOT_OVERRIDABLE.includes(root)) return "not overridable";
  const variable = configVariable(key.path);
  if (!variable) return "—";
  return variable.alias ? `${code(variable.name)} (or ${code(variable.alias)})` : code(variable.name);
}

const TARGET_TITLES: Record<string, string> = { entity: "entities", field: "fields", endpoint: "endpoints" };

/** The tags of a native, listed under its options. */
function nativeTagLines(native: ReturnType<typeof registeredNatives>[number]): string[] {
  return Object.entries(native.tags ?? {}).flatMap(([name, tag]) => [
    `#### \`@${name}\``,
    "",
    tag.description,
    "",
    `**Applies to:** ${tag.on.map((target) => TARGET_TITLES[target]).join(", ")}`,
    "",
    `**Options:** ${tag.options && tag.options.length > 0 ? tag.options.map((option) => code(option)).join(", ") : "none (a flag: \`@" + name + "\` or \`@" + name + " off\`)"}`,
    "",
    "```ts",
    tag.example,
    "```",
    "",
  ]);
}

/** One section per registered native, listing its options from its schema and its tags. */
function nativeSections(): string[] {
  return registeredNatives().flatMap((native) => [
    `### \`${native.key}\``,
    "",
    ...(native.docs?.summary ? [native.docs.summary, ""] : []),
    "| Key | Type | Default | Environment variable | Description |",
    "| --- | --- | --- | --- | --- |",
    ...describeOptions(native.schema, native.key).map(
      (option) =>
        `| ${code(option.path)} | ${code(option.type)} | ${option.default === undefined ? "—" : code(JSON.stringify(option.default))} | ${code(envNameFor(option.path))} | ${option.description ?? ""} |`,
    ),
    "",
    ...nativeTagLines(native),
  ]);
}

