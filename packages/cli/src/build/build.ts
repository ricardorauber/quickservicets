export const GENERATED_DIR = ".generated";

/**
 * Updates the generated folder in place, so editors watching it see ordinary file changes: writes only files whose
 * content changed and removes files that are no longer generated, never replacing the folder itself.
 */
export function writeGeneratedFiles(dir: string, files: Record<string, string>, keep: readonly string[] = []): void {
  mkdirSync(dir, { recursive: true });
  for (const entry of readdirSync(dir)) {
    if (!(entry in files) && !keep.includes(entry)) rmSync(join(dir, entry), { recursive: true, force: true });
  }
  for (const [name, content] of Object.entries(files)) {
    const file = join(dir, name);
    if (existsSync(file) && readFileSync(file, "utf8") === content) continue;
    writeFileSync(file, content);
  }
}

export interface BuildSummary {
  entities: number;
  endpoints: number;
  hooks: number;
  /** Features written in the project's `features/` folder. */
  features?: number;
  /** `Override:` lines: project features replacing natives, and project files replacing feature files. */
  overrides?: string[];
  /** Endpoints, hooks and jobs that come from features' folders. */
  fromFeatures?: { endpoints: number; hooks: number; jobs: number };
  /** Project paths of the enabled features' convention folders and `watch` lists, for `quickservicets dev`. */
  watch?: string[];
  /** The same paths by feature key, for the features with a build step, so `dev` reruns only the steps they feed. */
  buildInputs?: Record<string, string[]>;
  /** The features' build steps that ran, in order. */
  buildSteps?: BuildStepResult[];
  warnings: string[];
}

export const PENDING_MIGRATION_WARNING =
  'Model has changes without a migration. Run "quickservicets migration add <Name>"';

interface ResolvedEndpoint {
  route: EndpointRoute;
  /** The generated CRUD route the endpoint replaces. */
  override?: { entity: string; operation: CrudRouteEntry["operation"] };
  hooks: HookCall[];
  /** Typed query items of a GET or DELETE endpoint. */
  query?: QueryItem[];
  projection?: Projection;
  populate?: { entity: string; paths: string[] };
  /** Success status from `@status`. */
  status?: number;
  /** Feature tags written on the endpoint. */
  tags?: ParsedTags;
}

interface ScannedEndpoint {
  route: EndpointRoute;
  hooks: HookCall[];
  metadata: EndpointMetadata;
}

const HEADER = "// Generated by quickservicets build. Do not edit.";
const CRUD_ROUTES: [string, string, CrudRouteEntry["operation"]][] = [
  ["GET", "", "list"],
  ["GET", "/[id]", "read"],
  ["POST", "", "create"],
  ["PATCH", "/[id]", "update"],
  ["PUT", "/[id]", "replace"],
  ["DELETE", "/[id]", "delete"],
];

/** How a generated file imports a scanned file: through the core package for a native, by a relative path otherwise. */
export const importPath = (file: string) => (file.startsWith("@quickservicets/") ? file : `../${file}`);

/** The generated CRUD routes of every non-internal entity, with their resolved hooks. */
export function crudTable(models: EntityModel[]): CrudRouteEntry[] {
  return models
    .filter((model) => !model.internal)
    .flatMap((model) =>
      CRUD_ROUTES.map(([method, suffix, operation]) => ({
        method,
        path: `${entityRoutePath(model)}${suffix}`,
        entity: model.key,
        operation,
        hooks: resolveRouteHooks({ kind: "generated", entity: model, operation }),
      })),
    );
}

function overriddenRoute(route: EndpointRoute, models: EntityModel[]) {
  for (const entity of models) {
    if (entity.internal) continue;
    const operation = operationForRoute(entity, route.method, route.pattern);
    if (operation) return { entity, operation };
  }
  return undefined;
}

/**
 * The generated routes and endpoints with the feature tags that apply to each: a generated route its entity's, an
 * endpoint its own over those of the entity whose route it replaces.
 */
function taggedBuildRoutes(models: EntityModel[], endpoints: readonly ResolvedEndpoint[]): { method: string; path: string; entity?: string; tags?: ParsedTags }[] {
  const byKey = new Map(models.map((model) => [model.key, model]));
  const routes = new Map<string, { method: string; path: string; entity?: string; tags?: ParsedTags }>();
  for (const route of crudTable(models)) {
    const tags = byKey.get(route.entity)?.tags;
    routes.set(`${route.method} ${route.path}`, { method: route.method, path: route.path, entity: route.entity, ...(tags ? { tags } : {}) });
  }
  for (const endpoint of endpoints) {
    const key = `${endpoint.route.method} ${endpoint.route.path}`;
    const entity = endpoint.override?.entity;
    const tags = { ...(entity ? byKey.get(entity)?.tags : {}), ...endpoint.tags };
    routes.set(key, { method: endpoint.route.method, path: endpoint.route.path, ...(entity ? { entity } : {}), ...(Object.keys(tags).length > 0 ? { tags } : {}) });
  }
  return [...routes.values()];
}

/** Fails unless an `sse.ts` file's default export is a call of `defineSse`. */
function assertSseExport(source: string, file: string): void {
  const sourceFile = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
  const defined = sourceFile.statements.some((statement) => {
    if (!ts.isExportAssignment(statement) || statement.isExportEquals) return false;
    let expression = statement.expression;
    while (ts.isAsExpression(expression) || ts.isSatisfiesExpression(expression) || ts.isParenthesizedExpression(expression)) expression = expression.expression;
    return ts.isCallExpression(expression) && ts.isIdentifier(expression.expression) && expression.expression.text === "defineSse";
  });
  if (!defined) throw new BuildError(`${file}: must default-export defineSse(...)`);
}

/** Whether the resolved config serves Server-Sent Events: the `realtime` native with its `sse` item on. */
function sseEnabled(config: ResolvedConfig): boolean {
  const realtime = config.features.find((feature) => feature.key === "realtime");
  return (realtime?.options.sse as { enabled?: boolean } | undefined)?.enabled === true;
}

function resolveEndpoint(endpoint: ScannedEndpoint, models: EntityModel[], maxDepth: number): ResolvedEndpoint {
  const { route, metadata } = endpoint;
  const override = overriddenRoute(route, models);
  const readOverride = override && (override.operation === "list" || override.operation === "read") ? override : undefined;
  if (metadata.populate && !readOverride) {
    throw new BuildError(`${route.file}: @populate is only allowed on endpoints that override a list or read route`);
  }
  if (!override) {
    return { route, hooks: resolveRouteHooks({ kind: "custom", endpointHooks: endpoint.hooks }), projection: metadata.projection };
  }
  const { entity, operation } = override;
  const hooks = resolveRouteHooks({ kind: "override", entity, operation, endpointHooks: endpoint.hooks });
  const replaced = { entity: entity.key, operation };
  if (operation !== "list" && operation !== "read") return { route, override: replaced, hooks, projection: metadata.projection };

  const populatePaths = metadata.populate ?? entity.populate?.[operation] ?? [];
  for (const path of populatePaths) {
    const [error] = populatePathErrors(entity, models, path, maxDepth);
    if (error) throw new BuildError(`${route.file}: invalid @populate: ${error}`);
  }
  const populate = populatePaths.length > 0 ? { entity: entity.key, paths: populatePaths } : undefined;
  if (!metadata.projection) return { route, override: replaced, hooks, projection: entity.exposure[operation], populate };
  const paths = [...(metadata.projection.include ?? []), ...(metadata.projection.exclude ?? [])];
  const parsed = parseFieldPaths(entity, paths);
  if (!parsed.ok) throw new BuildError(`${route.file}: unknown path ${parsed.invalid.join(", ")} in @fields/@exclude`);
  return { route, override: replaced, hooks, projection: metadata.projection, populate };
}

export const GENERATED_INCLUDE_WARNING =
  'tsconfig.json includes ".generated", which TypeScript skips; use ".generated/**/*.ts" so endpoints and hooks see the generated types';

/** Warns about the old `include` entry that leaves the generated types out of the project. */
function generatedIncludeWarning(projectRoot: string): string | undefined {
  const file = join(projectRoot, "tsconfig.json");
  if (!existsSync(file)) return undefined;
  const { config } = ts.readConfigFile(file, (path) => readFileSync(path, "utf8"));
  const include = (config as { include?: unknown } | undefined)?.include;
  return Array.isArray(include) && include.includes(".generated") ? GENERATED_INCLUDE_WARNING : undefined;
}

/** Fails when an entity route or a custom endpoint takes a path the API docs reserve. */
function assertNoDocsConflicts(models: EntityModel[], routes: EndpointRoute[]): void {
  for (const model of models) {
    if (model.internal || model.link) continue;
    if (entityRoutePath(model).split("/").includes(DOCS_PATH.slice(1))) {
      throw new BuildError(`entities/${model.key}.ts: route ${entityRoutePath(model)} uses ${DOCS_PATH}, which is reserved for the API docs`);
    }
  }
  for (const route of routes) {
    if (route.method === "GET" && (route.path === DOCS_PATH || route.path === OPENAPI_PATH)) {
      throw new BuildError(`${route.file}: GET ${route.path} is reserved for the API docs`);
    }
  }
}

function assertEntityPopulateDepth(models: EntityModel[], maxDepth: number): void {
  for (const model of models) {
    for (const path of new Set([...(model.populate?.list ?? []), ...(model.populate?.read ?? [])])) {
      const [error] = populatePathErrors(model, models, path, maxDepth);
      if (error) throw new BuildError(`entities/${model.key}.ts: invalid @populate: ${error}`);
    }
  }
}

function generateRoutesFile(
  models: EntityModel[],
  endpoints: ResolvedEndpoint[],
  hooks: Map<string, HookEntry>,
): string {
  const hookNames = [...hooks.keys()].sort();
  const imports = [
    'import type { AppEndpoint, CrudRouteEntry, Endpoint, HookDefinition, SseDefinition } from "@quickservicets/core";',
    ...endpoints.map((endpoint, index) => `import endpoint${index} from ${JSON.stringify(importPath(endpoint.route.file))};`),
    ...hookNames.map((name) => `import hook_${name} from ${JSON.stringify(importPath(hooks.get(name)!.file))};`),
  ];
  const endpointEntries = endpoints.map(
    (endpoint, index) =>
      `  { method: ${JSON.stringify(endpoint.route.method)}, path: ${JSON.stringify(endpoint.route.path)}, hooks: ${JSON.stringify(endpoint.hooks)}, ${endpoint.projection ? `projection: ${JSON.stringify(endpoint.projection)}, ` : ""}${endpoint.populate ? `populate: ${JSON.stringify(endpoint.populate)}, ` : ""}${endpoint.query ? `query: ${JSON.stringify(endpoint.query)}, ` : ""}${endpoint.status !== undefined ? `status: ${endpoint.status}, ` : ""}${endpoint.route.feature ? `feature: ${JSON.stringify(endpoint.route.feature)}, ` : ""}${endpoint.route.kind ? `kind: ${JSON.stringify(endpoint.route.kind)}, ` : ""}${endpoint.tags ? `tags: ${JSON.stringify(endpoint.tags)}, ` : ""}handler: endpoint${index} as ${endpoint.route.kind === "sse" ? "SseDefinition" : "Endpoint"} },`,
  );
  return [
    HEADER,
    ...imports,
    "",
    `export const crudRoutes: CrudRouteEntry[] = ${JSON.stringify(crudTable(models), null, 2)};`,
    "",
    "export const endpoints: AppEndpoint[] = [",
    ...endpointEntries,
    "];",
    "",
    "export const hooks = new Map<string, HookDefinition>([",
    ...hookNames.map((name) => `  [${JSON.stringify(name)}, hook_${name}],`),
    "]);",
    "",
  ].join("\n");
}

/** The job registry: every job of `jobs/` keyed by its name, and the job names `req.jobs.run` accepts. */
export function generateJobsFile(jobs: JobEntry[]): string {
  return [
    HEADER,
    'import type { JobDefinition } from "@quickservicets/core";',
    ...jobs.map((entry, index) => `import job${index} from ${JSON.stringify(importPath(entry.file))};`),
    "",
    "export const jobs = new Map<string, JobDefinition>([",
    ...jobs.map((entry, index) => `  [${JSON.stringify(entry.name)}, ${entry.feature ? `{ ...job${index}, feature: ${JSON.stringify(entry.feature)} }` : `job${index}`}],`),
    "]);",
    "",
    'declare module "@quickservicets/core" {',
    "  interface JobNames {",
    ...jobs.map((entry) => `    ${JSON.stringify(entry.name)}: true;`),
    "  }",
    "}",
    "",
  ].join("\n");
}

