import { posix } from "node:path";
import type { DeploymentModel } from "./model.ts";

/** What a generator's `generate` receives besides the model. */
export interface GeneratorContext {
  /** The resolved options of the feature that registered the generator. */
  options: Record<string, unknown>;
  /** The files of the feature's `templates/` folder, by path relative to it. */
  templates: Readonly<Record<string, string>>;
  /** Adds a file to the generator's output folder; a path leaving the folder throws. */
  write(path: string, content: string): void;
}

/** A deployment generator: writes files (infrastructure code, manifests, pipelines) from the deployment model. */
export interface DeployGenerator {
  generate(model: DeploymentModel, context: GeneratorContext): void | Promise<void>;
  /** The output folder relative to the project (default `deploy/<key>/`). */
  out?: string;
}

/** The generators features registered with `ctx.feature("deploy").generator`, by key, with their owners. */
const STORE = Symbol.for("quickservicets.deploy.generators");
const store = ((globalThis as unknown as Record<symbol, Map<string, { generator: DeployGenerator; owner: string }>>)[STORE] ??= new Map());

/** The generators registered in this process, by key. */
export function deployGenerators(): ReadonlyMap<string, { generator: DeployGenerator; owner: string }> {
  return store;
}

/** Forgets the registered generators, before the setups that register them run again. */
export function clearDeployGenerators(): void {
  store.clear();
}

/** Registers a generator under a key; a key registered twice fails naming both owners. */
export function addDeployGenerator(key: string, generator: DeployGenerator, owner: string): void {
  if (!/^[a-z][a-z0-9-]*$/.test(key)) throw new Error(`Invalid deploy generator key ${JSON.stringify(key)}: use lowercase letters, digits and -`);
  if (typeof generator?.generate !== "function") throw new Error(`Invalid deploy generator ${key} of ${owner}: expected { generate(model, context) }`);
  const taken = store.get(key);
  if (taken) throw new Error(`Deploy generator ${key} is registered by ${taken.owner} and ${owner}; keep one`);
  store.set(key, { generator, owner });
}

/** The message of the command when no generator is registered. */
export const NO_GENERATORS = "No deploy generators are registered; enable a feature that registers one";

/** The first line every generated file starts with, in its format's comment syntax. */
export const GENERATED_HEADER = "Generated by quickservicets deploy generate from quickservicets.config.ts";

/** A file's content with the generated header, in the comment syntax of its format; formats without comments (JSON) are left as they are. */
export function withHeader(path: string, content: string): string {
  const name = posix.basename(path).toLowerCase();
  const extension = name.includes(".") ? name.slice(name.lastIndexOf(".")) : "";
  if (extension === ".json") return content;
  if ([".ts", ".js", ".mjs", ".cjs", ".tsx", ".jsx", ".go", ".java", ".kt", ".cs", ".bicep", ".hcl", ".jsonc"].includes(extension)) return `// ${GENERATED_HEADER}\n${content}`;
  if ([".md", ".html", ".xml", ".svg"].includes(extension)) return `<!-- ${GENERATED_HEADER} -->\n${content}`;
  if ([".sql", ".lua"].includes(extension)) return `-- ${GENERATED_HEADER}\n${content}`;
  if (extension === ".ini") return `; ${GENERATED_HEADER}\n${content}`;
  // YAML, TOML, Terraform, shell, Dockerfile, .env, plain text and the rest take #.
  return `# ${GENERATED_HEADER}\n${content}`;
}

/** The normalized path of a file inside a generator's folder, or throws when it leaves the folder. */
export function generatorFilePath(out: string, path: string): string {
  const normalized = posix.normalize(path.replaceAll("\\", "/"));
  if (normalized.startsWith("../") || normalized === ".." || posix.isAbsolute(normalized) || normalized === "." || normalized === "") throw new Error(`Generated file ${path} leaves ${out}`);
  return normalized;
}

/** Runs a generator on the model and resolves its files, by path inside its folder, each with the header. */
export async function runDeployGenerator(key: string, generator: DeployGenerator, model: DeploymentModel, context: Omit<GeneratorContext, "write">): Promise<{ out: string; files: Map<string, string> }> {
  const out = (generator.out ?? (typeof context.options.out === "string" ? context.options.out : undefined) ?? `deploy/${key}`).replace(/\/+$/, "");
  const files = new Map<string, string>();
  await generator.generate(model, { ...context, write: (path, content) => void files.set(generatorFilePath(`${out}/`, path), withHeader(path, String(content))) });
  return { out, files };
}

/**
 * Renders a template's `{{ name }}` placeholders (dotted paths like `{{ health.live }}`) from `values`; a path with no
 * value throws `Unknown template value <path>`.
 */
export function renderTemplate(template: string, values: object): string {
  return template.replace(/\{\{\s*([A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*)\s*\}\}/g, (_, path: string) => {
    let current: unknown = values;
    for (const part of path.split(".")) current = current === null || current === undefined ? undefined : (current as Record<string, unknown>)[part];
    if (current === undefined || current === null) throw new Error(`Unknown template value ${path}`);
    return typeof current === "object" ? JSON.stringify(current) : String(current);
  });
}

/** The secret values that appear in generated files, by file; an empty list when none does. */
export function secretsInFiles(files: ReadonlyMap<string, string>, secrets: readonly string[]): { file: string; secret: string }[] {
  const found: { file: string; secret: string }[] = [];
  for (const [file, content] of files) for (const secret of secrets) if (secret.length >= 4 && content.includes(secret)) found.push({ file, secret });
  return found;
}
