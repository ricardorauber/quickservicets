describe.skipIf(!docker)("with Docker", () => {
  test("dev --services starts PostgreSQL for each database and Redis, and the project connects with the injected variables", async () => {
    const [main, orders, redis] = [freePort(), freePort(), freePort()];
    const name = `qs_b13_dev_${crypto.randomUUID().slice(0, 8)}`;
    const root = project({
      "quickservicets.config.ts": config(
        `{ database: postgresAdapter({ url: process.env.DATABASE_URL ?? "" }), databases: { orders: postgresAdapter({ url: process.env.QS_DATABASES_ORDERS_URL ?? "" }) }, "test-redis-queue": {}, dev: { project: "${name.replaceAll("_", "-")}", services: { database: { port: ${main} }, "database-orders": { port: ${orders} }, redis: { port: ${redis} } } } }`,
      ),
    });
    const { out, err, output } = lines();
    const injected = await startDevServices(root, output, {});
    try {
      if (typeof injected === "number") throw new Error(err.join("\n"));
      expect(out).toHaveLength(3);
      const compose = readFileSync(join(root, ".generated/dev/compose.yml"), "utf8");
      expect(compose).toContain("healthcheck:");
      expect(compose).toContain(`name: ${name.replaceAll("_", "-")}_redis_data`);
      expect(Object.keys(injected).sort()).toEqual(["DATABASE_URL", "QS_DATABASES_ORDERS_URL", "REDIS_URL"]);
      for (const url of [injected.DATABASE_URL!, injected.QS_DATABASES_ORDERS_URL!]) {
        const adapter = postgresAdapter({ url });
        await adapter.connect([], {});
        try {
          await adapter.ping?.();
        } finally {
          await adapter.disconnect();
        }
      }
      const { RedisClient } = await import("bun");
      const client = new RedisClient(injected.REDIS_URL);
      try {
        expect(await client.ping()).toBe("PONG");
      } finally {
        client.close();
      }
      // `.env` now holds both database connections.
      expect(existsSync(join(root, ".env"))).toBe(true);
      expect(readFileSync(join(root, ".env"), "utf8")).toContain(`QS_DATABASES_ORDERS_URL=postgres://postgres:postgres@localhost:${orders}/app`);
    } finally {
      const resolved = await loadConfig(root, {});
      await stopLocalServices({ root, config: resolved as never, options: resolved.features.find((feature) => feature.key === "dev")!.options as never, log: () => {} }, true);
    }
  }, 180_000);
});
