import { expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { composeYaml, INFRA_CATALOG, loadConfig, localServicesPlan, type DevOptions } from "@quickservicets/core";
import { startTestService } from "@quickservicets/cli/testing";

const root = join(import.meta.dir, "..");
const read = (path: string) => readFileSync(join(root, path), "utf8");

test("the compose document has the project's PostgreSQL with its health check, volume and port, without Docker", async () => {
  const config = await loadConfig(root, {});
  const options = config.features.find((feature) => feature.key === "dev")!.options as unknown as DevOptions;
  const plan = localServicesPlan(config as never, options, root);
  expect(plan.project).toBe("minimal-dev");
  expect(plan.services.map((service) => [service.name, service.image, service.port])).toEqual([["database", INFRA_CATALOG.postgres.image, 5432]]);
  const yaml = composeYaml(plan.document);
  expect(yaml.split("\n")[0]).toBe("# Generated by quickservicets from quickservicets.config.ts. Do not edit.");
  expect(yaml).toContain("pg_isready -U postgres");
  expect(yaml).toContain("name: minimal-dev_database_data");
  expect(plan.env).toEqual({ DATABASE_URL: "postgres://postgres:postgres@localhost:5432/app" });
});

test("the project serves its posts", async () => {
  const service = await startTestService({ files: { "quickservicets.config.ts": read("quickservicets.config.ts"), "entities/Post.ts": read("entities/Post.ts") } });
  try {
    expect((await service.fetch("/posts", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ title: "Hello" }) })).status).toBe(201);
    expect(((await (await service.fetch("/posts")).json()) as { total: number }).total).toBe(1);
  } finally {
    await service.stop();
  }
});
