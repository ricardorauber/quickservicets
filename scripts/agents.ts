/** The repository path of the docs page a site link like `/guides/entities/#tags` points to, keeping the anchor. */
export function repositoryLink(link: string, root: string = ROOT): string {
  if (!link.startsWith("/")) return link;
  const [path = "", anchor] = link.split("#", 2) as [string, string | undefined];
  const page = path.replace(/^\/+|\/+$/g, "");
  const candidates = page === "" ? ["index.mdx", "index.md"] : [`${page}.md`, `${page}.mdx`, `${page}/index.md`, `${page}/index.mdx`];
  const found = candidates.find((candidate) => existsSync(join(root, CONTENT, candidate)));
  return found ? `${CONTENT}/${found}${anchor ? `#${anchor}` : ""}` : link;
}

/** A topic's body for another document: without its heading and summary, headings moved down by `levels`. */
function embed(topic: AgentTopic, levels: number, root: string): string {
  return topic.markdown
    .split("\n")
    .slice(3)
    .join("\n")
    .replace(/^(#+) /gm, (_, hashes: string) => `${"#".repeat(hashes.length + levels)} `)
    .replace(/\]\((\/[^)\s]*)\)/g, (_, link: string) => `](${repositoryLink(link, root)})`)
    .trim();
}

