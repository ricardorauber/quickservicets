/**
 * Writes the deterministic seed as SQL (truncate + COPY) and the k6 fixtures (the seeded ids).
 *
 *   bun benchmarks/seed/seed.ts --sql seed.sql --fixtures fixtures.json
 *   bun benchmarks/seed/seed.ts | psql postgres://bench:bench@localhost:55432/bench
 *
 * The SQL expects the tables of benchmarks/schema/schema.sql and empties them first, so it can be applied again
 * between scenarios to return to the same state.
 */
import { generateDataset } from "./data.ts";

export function seedSql(): string {
  const { users, organizations } = generateDataset();
  const lines: string[] = [
    "-- Generated by benchmarks/seed/seed.ts. Deterministic: the same output on every run.",
    "BEGIN;",
    "TRUNCATE organizations__members, organizations, users, media, files;",
    "COPY users (id, created_at, updated_at, email, name, role, age) FROM stdin;",
  ];
  for (const u of users) {
    lines.push([u.id, u.createdAt, u.updatedAt, u.email, u.name, u.role, u.age ?? "\\N"].join("\t"));
  }
  lines.push("\\.");
  lines.push("COPY organizations (id, created_at, updated_at, name, slug) FROM stdin;");
  for (const o of organizations) lines.push([o.id, o.createdAt, o.updatedAt, o.name, o.slug].join("\t"));
  lines.push("\\.");
  lines.push("COPY organizations__members (owner_id, target_id, position) FROM stdin;");
  for (const o of organizations) o.members.forEach((member, position) => lines.push([o.id, member, position].join("\t")));
  lines.push("\\.");
  lines.push("COMMIT;");
  lines.push("ANALYZE users;");
  lines.push("ANALYZE organizations;");
  lines.push("ANALYZE organizations__members;");
  return lines.join("\n") + "\n";
}

export function fixtures(): { users: string[]; organizations: string[] } {
  const { users, organizations } = generateDataset();
  return { users: users.map((u) => u.id), organizations: organizations.map((o) => o.id) };
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const option = (name: string) => {
    const index = args.indexOf(name);
    return index === -1 ? undefined : args[index + 1];
  };
  const sqlPath = option("--sql");
  const fixturesPath = option("--fixtures");
  if (fixturesPath) await Bun.write(fixturesPath, JSON.stringify(fixtures()));
  if (sqlPath) await Bun.write(sqlPath, seedSql());
  if (!sqlPath && !fixturesPath) process.stdout.write(seedSql());
}
