import { readFileSync } from "node:fs";
import { join } from "node:path";
import ts from "typescript";
import { COMMANDS } from "../../packages/cli/src/commands.ts";
import { documentedEntityTags } from "../../packages/cli/src/entities/entity-tags.ts";
import { documentedFieldTags } from "../../packages/cli/src/entities/field-tags.ts";
import { documentedEndpointTags } from "../../packages/cli/src/hooks/endpoint-tags.ts";
import type { DocumentedTag } from "../../packages/cli/src/tag-docs.ts";

export const REPO = join(import.meta.dir, "../..");
export const CONTENT = join(REPO, "docs/src/content/docs");
export const TRANSLATIONS = join(REPO, "docs/i18n/reference.pt-br.json");
const HEADER = "{/* Generated by `bun run docs:reference`. Do not edit by hand. */}";

export type Locale = "en" | "pt-br";

/** Looks up Portuguese texts by key; English texts are passed through. Missing keys are collected. */
export class Texts {
  readonly missing: string[] = [];
  /** English text of every key looked up, for writing translations. */
  readonly english: Record<string, string> = {};
  private readonly portuguese: Record<string, string>;

  constructor(
    readonly locale: Locale,
    portuguese?: Record<string, string>,
  ) {
    this.portuguese = portuguese ?? (JSON.parse(readFileSync(TRANSLATIONS, "utf8")) as Record<string, string>);
  }

  t(key: string, english: string): string {
    this.english[key] = english;
    if (this.locale === "en") return english;
    const text = this.portuguese[key];
    if (text === undefined) {
      this.missing.push(key);
      return english;
    }
    return text;
  }
}

export interface ConfigKey {
  path: string;
  type: string;
  description?: string;
  defaultValue?: string;
}

/** Every key of `ServiceConfig`, nested ones included, with its type, doc comment and documented default. */
export function configKeys(): ConfigKey[] {
  const file = join(REPO, "packages/core/src/config.ts");
  const source = ts.createSourceFile(file, readFileSync(file, "utf8"), ts.ScriptTarget.ESNext, true);
  const config = source.statements.find((statement): statement is ts.InterfaceDeclaration => ts.isInterfaceDeclaration(statement) && statement.name.text === "ServiceConfig");
  if (!config) throw new Error("ServiceConfig not found");
  const keys: ConfigKey[] = [];
  const visit = (members: ts.NodeArray<ts.TypeElement>, prefix: string) => {
    for (const member of members) {
      if (!ts.isPropertySignature(member) || !member.type) continue;
      const path = `${prefix}${member.name.getText(source)}`;
      const doc = ts
        .getJSDocCommentsAndTags(member)
        .filter(ts.isJSDoc)
        .map((comment) => ts.getTextOfJSDocComment(comment.comment) ?? "")
        .join(" ")
        .trim();
      const defaultValue = /\(default:? ([^)]*)\)/.exec(doc)?.[1] ?? /defaults to ([^.;]*)/.exec(doc)?.[1];
      const nested = ts.isTypeLiteralNode(member.type) ? member.type : undefined;
      keys.push({
        path,
        type: nested ? "object" : member.type.getText(source).replace(/\s+/g, " "),
        ...(doc ? { description: doc } : {}),
        ...(defaultValue ? { defaultValue: defaultValue.trim() } : {}),
      });
      if (nested) visit(nested.members, `${path}.`);
    }
  };
  visit(config.members, "");
  return keys;
}

const code = (text: string) => `\`${text.replaceAll("|", "\\|")}\``;
const frontmatter = (title: string, description: string) => `---\ntitle: ${title}\ndescription: ${description}\n---\n\n${HEADER}\n`;

function tagSection(kind: string, tag: DocumentedTag, texts: Texts): string {
  const key = `tag.${kind}.${tag.name}`;
  return [
    `### \`@${tag.name}\``,
    "",
    texts.t(`${key}.description`, tag.description ?? ""),
    "",
    `**${texts.t("label.appliesTo", "Applies to")}:** ${texts.t(`${key}.appliesTo`, tag.appliesTo ?? "")}`,
    "",
    "```ts",
    tag.example ?? "",
    "```",
    "",
  ].join("\n");
}

function tagsPage(texts: Texts): string {
  const groups: [string, string, string, DocumentedTag[]][] = [
    ["entity", texts.t("tags.entity.title", "Entity tags"), texts.t("tags.entity.intro", "Written in the JSDoc comment above an entity type. Any other tag on an entity names a hook from `hooks/`."), documentedEntityTags()],
    ["field", texts.t("tags.field.title", "Field tags"), texts.t("tags.field.intro", "Written in the JSDoc comment above a field of an entity."), documentedFieldTags()],
    ["endpoint", texts.t("tags.endpoint.title", "Endpoint tags"), texts.t("tags.endpoint.intro", "Written in the JSDoc comment above an endpoint's default export. Any other tag names a hook from `hooks/`."), documentedEndpointTags()],
  ];
  return [
    frontmatter(texts.t("tags.title", "JSDoc tags"), texts.t("tags.description", "Every built-in tag for entities, fields and endpoints.")),
    texts.t("tags.intro", "Tags configure entities, fields and endpoints. This page lists every built-in tag; it is generated from the framework's tag registries."),
    "",
    ...groups.flatMap(([kind, title, intro, tags]) => [`## ${title}`, "", intro, "", ...tags.map((tag) => tagSection(kind, tag, texts))]),
  ].join("\n");
}

function configPage(texts: Texts): string {
  const rows = configKeys().map(
    (key) =>
      `| ${code(key.path)} | ${code(key.type)} | ${key.defaultValue ? texts.t(`config.${key.path}.default`, key.defaultValue) : "—"} | ${texts.t(`config.${key.path}`, key.description ?? "")} |`,
  );
  return [
    frontmatter(texts.t("config.title", "Configuration"), texts.t("config.description", "Every key of quickservice.config.ts.")),
    texts.t("config.intro", "The project configuration lives in `quickservice.config.ts` and is written with `defineConfig({ ... })`. Nested keys are shown with dots."),
    "",
    `| ${texts.t("label.key", "Key")} | ${texts.t("label.type", "Type")} | ${texts.t("label.default", "Default")} | ${texts.t("label.description", "Description")} |`,
    "| --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

function cliPage(texts: Texts): string {
  return [
    frontmatter(texts.t("cli.title", "CLI"), texts.t("cli.description", "Every command of the quickservice CLI.")),
    texts.t("cli.intro", "Run the commands with `bun run quickservice <command>` inside a project."),
    "",
    ...COMMANDS.flatMap((command) => [
      `## \`${command.name}\``,
      "",
      texts.t(`cli.${command.name}`, command.description),
      "",
      "```bash",
      command.usage,
      "```",
      "",
    ]),
  ].join("\n");
}

/** Page generators keyed by their path inside a locale's `reference/` folder. */
export const REFERENCE_PAGES: Record<string, (texts: Texts) => string> = {
  "tags.mdx": tagsPage,
  "config.mdx": configPage,
  "cli.mdx": cliPage,
};

/** Every generated page, keyed by its path inside the content folder; throws when Portuguese texts are missing. */
export function referencePages(portuguese?: Record<string, string>): Record<string, string> {
  const pages: Record<string, string> = {};
  for (const locale of ["en", "pt-br"] as const) {
    const texts = new Texts(locale, portuguese);
    for (const [name, page] of Object.entries(REFERENCE_PAGES)) {
      pages[`${locale === "en" ? "" : "pt-br/"}reference/${name}`] = page(texts);
    }
    if (texts.missing.length > 0) throw new Error(`Missing Portuguese translations: ${[...new Set(texts.missing)].join(", ")}`);
  }
  return pages;
}
